function inside(lon: number, lat: number, polygon: [number, number][]) {
  let result = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i];
    const [xj, yj] = polygon[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) result = !result;
  }
  return result;
}

// Küre yüzeyine eşit aralıklı noktalar dizip yalnızca karaya düşenleri döndürür: [enlem, boylam] (radyan).
export function buildLandDots(step = 2.6): { lat: number; lon: number }[] {
  const dots: { lat: number; lon: number }[] = [];
  for (let lat = -58; lat <= 82; lat += step) {
    const stepLon = step / Math.max(0.18, Math.cos((lat * Math.PI) / 180));
    for (let lon = -180; lon < 180; lon += stepLon) {
      if (landPolygons.some((polygon) => inside(lon, lat, polygon))) dots.push({ lat: (lat * Math.PI) / 180, lon: (lon * Math.PI) / 180 });
    }
  }
  return dots;
}

